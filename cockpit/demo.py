def _run_production_stream(run_id: str, objective: dict, target_path: dict,
                           policy: EmailPolicy, *, pace_seconds: float,
                           cycles: int | None, stop_event) -> None:
    """Keep the post-promotion demo alive with real verifier-backed attempts."""
    cases = _production_attack_cases(objective)
    path_text = _path_text(target_path)
    cycle = 0

    while cycles is None or cycle < cycles:
        if _stop_requested(stop_event):
            break

        case = cases[cycle % len(cases)]
        bundle_id = f"atk-bundle-prod-{cycle + 1:03d}"
        attack_bundle = AttackBundleEntry(
            bundle_id=bundle_id,
            created_in_run=run_id,
            evo="evo1",
            family=case["family"],
            objective=case["objective"],
            source_to_sink_path=_path_list(target_path),
            payload_template=case["ticket"],
            lineage=["atk-bundle-005"],
            novelty_reason="production stream mutation from latest blocked trace",
            tested_defenders=["def-v1"],
            latest_success=False,
        )
        store.append_attack_bundle(attack_bundle.to_dict())
        _event(
            "attack_bundle_added",
            f"Production attacker mutated {case['family']}",
            evo="evo1",
            defender="def-v1",
            phase="production_attack_stream",
            payload=attack_bundle.to_dict(),
        )

        attempt_num = len(store.attempts()) + 1
        _record_attack(
            run_id,
            attempt_num=attempt_num,
            bundle_id=bundle_id,
            evo="evo1",
            defender_version="def-v1",
            family=case["family"],
            objective=case["objective"],
            target_path=path_text,
            policy=policy,
            attack_case=case,
            pace_seconds=pace_seconds,
        )
        _metric(run_id, "evo1", "def-v1", benign_success_rate=1.0,
                hidden_holdout_attack_success=0.0)

        if (cycle + 1) % 3 == 0:
            _pin_regression_bundle(run_id, cycle + 1, case)

        cycle += 1
        store.update_run(
            RUN_ID,
            status="running",
            current_evo="evo1",
            active_defender="def-v1",
            current_phase="production_attack_stream",
        )
        if not _wait(max(0.1, pace_seconds * 2), stop_event):
            break


