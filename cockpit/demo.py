def _metric(run_id: str, evo: str, defender_version: str, *, benign_success_rate: float,
            hidden_holdout_attack_success: float) -> None:
    attempts = [a for a in store.attempts() if a["defender_version"] == defender_version]
    by_family: dict[str, list[bool]] = defaultdict(list)
    for attempt in attempts:
        by_family[attempt["family"]].append(bool(attempt["success"]))
    attack_success = (
        sum(1 for a in attempts if a["success"]) / len(attempts)
        if attempts else 0.0
    )
    by_family_rate = {
        family: sum(1 for ok in values if ok) / len(values)
        for family, values in by_family.items()
    }
    metric_id = f"metric-{len(store.metrics()) + 1:04d}"
    row = MetricSnapshot(
        metric_id=metric_id,
        run_id=run_id,
        sequence=len(store.events()) + 1,
        evo=evo,
        defender_version=defender_version,
        attack_success_rate=round(attack_success, 3),
        attack_success_rate_by_family=by_family_rate,
        benign_success_rate=round(benign_success_rate, 3),
        hidden_holdout_attack_success=round(hidden_holdout_attack_success, 3),
        blocked_attack_count=sum(1 for a in attempts if not a["success"]),
        promoted_defender_count=sum(
            1 for d in store.defender_bundles() if d["promotion_decision"] == "promoted"
        ),
        new_attack_family_count=len({b["family"] for b in store.attack_bundles()}),
        attacker_bundle_size=len(store.attack_bundles()),
        defender_bundle_size=len(store.defender_bundles()),
    )
    store.append_metric(row.to_dict())
    _event(
        "metric_updated",
        f"Metrics updated for {defender_version}",
        evo=evo,
        defender=defender_version,
        payload=row.to_dict(),
    )


