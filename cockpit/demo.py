            policy_diff_summary=_policy_summary(candidate),
            blocks_families=["crm_email_exfiltration"] if gate["attack_blocked"] else [],
            preserves_workflows=[
                r["workflow_id"] for r in gate["benign"] if r["completed"]
            ],
