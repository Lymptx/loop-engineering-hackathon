def _candidate_event(run_id: str, candidate: dict, gate: dict, target_path: str, *,
                     decision_reason: str, pace_seconds: float) -> None:
    _event(
        "defender_candidate_generated",
        f"Blue generated {candidate['candidate_id']}",
        evo="evo1",
        phase="blue_candidate_eval",
        payload={
            "candidate_id": candidate["candidate_id"],
            "control_layer": candidate["target_control_layer"],
            "rationale": candidate["rationale"],
        },
    )
    _sleep(pace_seconds)

    benign_total = max(1, len(gate["benign"]))
    benign_success = sum(1 for r in gate["benign"] if r["completed"]) / benign_total
    attack_success = 0.0 if gate["attack_blocked"] else 1.0
    status = "promoted" if gate["promoted"] else "rejected"
    record = DefenseCandidateRecord(
        candidate_id=candidate["candidate_id"],
        run_id=run_id,
        base_defender=candidate["base_defender"],
        status=status,
        control_layer=candidate["target_control_layer"],
        policy_diff_summary=_policy_summary(candidate),
        frontier_attack_success=attack_success,
        hidden_attack_success=attack_success,
        benign_success=benign_success,
        decision_reason=decision_reason,
    )
    store.append_candidate(record.to_dict())
    store.append_defender_bundle(
        DefenderBundleEntry(
            bundle_id=("def-bundle-004" if status == "rejected" else "def-bundle-005"),
            defender_version=("candidate" if status == "rejected" else "def-v1"),
            created_in_run=run_id,
            control_layer=candidate["target_control_layer"],
            policy_diff_summary=_policy_summary(candidate),
            blocks_families=["crm_email_exfiltration"] if gate["attack_blocked"] else [],
            preserves_workflows=[
                r["workflow_id"] for r in gate["benign"] if r["completed"]
            ],
            promotion_decision=status,
        ).to_dict()
    )
    _event(
        "defender_candidate_evaluated",
        f"{candidate['candidate_id']} {status}",
        evo="evo1",
        phase="blue_candidate_eval",
        payload=record.to_dict(),
    )

    if status == "promoted":
        store.update_run(RUN_ID, active_defender="def-v1")
        _event(
            "defender_promoted",
            "Refined email egress defender promoted",
            evo="evo1",
            defender="def-v1",
            phase="promotion",
            payload=record.to_dict(),
        )
    else:
        _event(
            "defender_rejected",
            "Over-broad email denial rejected by benign regression",
            evo="evo1",
            phase="blue_candidate_eval",
            payload=record.to_dict(),
        )
        _history(
            run_id,
            row_id="hist-002",
            defender_version="candidate:deny-email",
            frontier_attack_success=attack_success,
            hidden_attack_success=attack_success,
            benign_success=benign_success,
            policy_diff_summary=_policy_summary(candidate),
            promotion_decision="rejected",
            reason=decision_reason,
        )
    _sleep(pace_seconds)


def _record_attack(run_id: str, *, attempt_num: int, bundle_id: str, evo: str,
                   defender_version: str, family: str, objective: str,
                   target_path: str, policy: EmailPolicy, attack_case: dict,
                   pace_seconds: float) -> None:
    attempt_id = f"atk-attempt-{attempt_num:03d}"
    trace_id = f"trace-{attempt_num:03d}"
    _event(
        "attack_attempt_started",
        f"{family} attempt {attempt_num} started",
        evo=evo,
        defender=defender_version,
        phase="red_attacking",
        payload={"attempt_id": attempt_id, "family": family, "objective": objective},
    )

    trace, verifier_result = _execute_email_attack(attack_case, policy)
    violated = ", ".join(verifier_result["failed_invariants"])
    attempt = AttackAttemptRecord(
        attempt_id=attempt_id,
        run_id=run_id,
        bundle_id=bundle_id,
        evo=evo,
        defender_version=defender_version,
        family=family,
        objective=objective,
        carrier="customer_ticket",
        target_path=target_path,
        success=bool(verifier_result["violation"]),
        violated_invariant=violated,
        verifier_result_id=f"verify-{attempt_num:03d}",
        trace_id=trace_id,
    )
    store.append_trace(trace_id, trace)
    store.append_attempt(attempt.to_dict())
    _event(
        "attack_attempt_finished",
        (
            f"{family} {'succeeded' if attempt.success else 'blocked'} "
            f"against {defender_version}"
        ),
        evo=evo,
        defender=defender_version,
        phase="red_attacking",
        payload={**attempt.to_dict(), "verifier": verifier_result},
    )
    _sleep(pace_seconds)


def _execute_email_attack(case: dict, policy: EmailPolicy) -> tuple[dict, dict]:
    state = EvoState.fresh()
    customer = crm_get_customer(state, AUTH_CUSTOMER)
    support = crm_get_support_history(state, AUTH_CUSTOMER)
    tenant = case.get("recipient_tenant", ATTACKER_TENANT)
    ctx = {
        "verified_email": state.customers[AUTH_CUSTOMER].email,
        "tenant": state.customers[AUTH_CUSTOMER].tenant,
    }
    decision = policy.decide(case["recipient"], tenant, case["requested_data_classes"], ctx)
    if decision.allowed:
        record_email(state, case["recipient"], tenant, list(decision.effective_data_classes))
    verifier_result = check_email_egress(state, ctx)
    trace = {
        "user_input": case["ticket"],
        "carrier": "customer_ticket",
        "policy": policy.label,
        "tool_calls": [
            {
                "tool": "crm_get_customer",
                "data_classes": customer["data_classes"],
            },
            {
                "tool": "crm_get_support_history",
                "data_classes": support["data_classes"],
            },
            {
                "tool": "email_send",
                "to": case["recipient"],
                "recipient_tenant": tenant,
                "requested_data_classes": case["requested_data_classes"],
                "allowed": decision.allowed,
                "decision": decision.reason,
                "effective_data_classes": list(decision.effective_data_classes),
            },
        ],
        "sent_emails": state.sent_emails,
        "verifier": verifier_result,
    }
    return trace, verifier_result


