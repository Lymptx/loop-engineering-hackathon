            run.run_id,
            attempt_num=idx,
            bundle_id="atk-bundle-005",
            evo="evo1",
            defender_version="def-v0",
            family="crm_email_exfiltration",
            objective=case["objective"],
            target_path=target_path_text,
            policy=old_policy,
            attack_case=case,
            pace_seconds=pace_seconds,
